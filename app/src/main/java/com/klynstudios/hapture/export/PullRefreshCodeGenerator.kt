package com.klynstudios.hapture.export

import com.klynstudios.hapture.core.physics.PullRefreshSolver

/**
 * Same deterministic-template policy as [SpringCodeGenerator]. The trigger
 * check and the rubber band are copied as is from
 * [com.klynstudios.hapture.core.physics.PullRefreshSolver] and
 * [com.klynstudios.hapture.core.physics.RubberBand]; the hold is a plain `delay`,
 * the return is a real `spring()`.
 */
object PullRefreshCodeGenerator {

    fun generate(
        stiffness: Float,
        dampingRatio: Float,
        triggerDp: Float,
        holdMs: Float,
        resistanceK: Float,
    ): String {
        val stiffnessStr = DesignSpec.num(stiffness, 1)
        val dampingStr = DesignSpec.num(dampingRatio, 2)
        val triggerStr = DesignSpec.num(triggerDp, 0)
        val holdStr = DesignSpec.num(holdMs, 0)
        val kStr = DesignSpec.num(resistanceK, 4)

        return """
            |// Generated by Hapture -- pull to refresh with an elastic pull and a real settle spring.
            |${ComposeImports.GESTURE}
            |
            |// Resistance is relative to the trigger distance, so every setting can be pulled past the line.
            |private fun rubberBand(raw: Float, k: Float, trigger: Float): Float {
            |    return raw / (1 + k * ${PullRefreshSolver.RESISTANCE_SCALE.toInt()}f / trigger * kotlin.math.abs(raw))
            |}
            |
            |@Composable
            |fun HapturePullToRefresh(
            |    onRefresh: suspend () -> Unit,
            |    modifier: Modifier = Modifier,
            |    content: @Composable () -> Unit,
            |) {
            |    val density = LocalDensity.current
            |    val trigger = with(density) { ${triggerStr}.dp.toPx() }
            |    val resistanceK = ${kStr}f
            |    val offsetY = remember { Animatable(0f) }
            |    val scope = rememberCoroutineScope()
            |
            |    Box(
            |        // offset/scale first, so whatever look you pass in modifier (size, background) moves with it.
            |        modifier = Modifier
            |            .offset { IntOffset(0, offsetY.value.roundToInt()) }
            |            .then(modifier)
            |            .pointerInput(Unit) {
            |                var raw = 0f
            |                var triggered = false
            |                detectDragGestures(
            |                    onDragStart = { raw = offsetY.value; triggered = false },
            |                    onDrag = { change, dragAmount ->
            |                        change.consume()
            |                        raw += dragAmount.y
            |                        val visual = rubberBand(raw, resistanceK, trigger)
            |                        triggered = visual >= trigger
            |                        scope.launch { offsetY.snapTo(visual) }
            |                    },
            |                    onDragEnd = {
            |                        scope.launch {
            |                            if (triggered) {
            |                                offsetY.animateTo(trigger, spring(dampingRatio = ${dampingStr}f, stiffness = ${stiffnessStr}f))
            |                                onRefresh()
            |                                delay(${holdStr}L)
            |                            }
            |                            offsetY.animateTo(0f, spring(dampingRatio = ${dampingStr}f, stiffness = ${stiffnessStr}f))
            |                        }
            |                    },
            |                )
            |            },
            |    ) { content() }
            |}
        """.trimMargin()
    }
}
